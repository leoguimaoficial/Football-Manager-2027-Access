// Compares only GPL project text sources. Never reads game binaries or user saves.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),upstream=path.join(root,'.upstream/fm26');
const projects=['Host','Plugin','Navigation','Speech','Tests','CompanionApp'];
const extensions=new Set(['.cs','.js','.css','.json','.csproj']);
function walk(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>{
  if(e.isDirectory())return ['bin','obj','node_modules','.git'].includes(e.name)?[]:walk(path.join(dir,e.name));
  return extensions.has(path.extname(e.name))?[path.join(dir,e.name)]:[];
});}
const normalize=s=>s.replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const rows=[];
for(const project of projects){
  const originalRoot=path.join(upstream,'FM26Access.'+project),currentRoot=path.join(root,'FM27Access.'+project);
  const originalFiles=walk(originalRoot),known=new Set();
  for(const file of originalFiles){
    const rel=path.relative(originalRoot,file).replaceAll('FM26Access','FM27Access'),current=path.join(currentRoot,rel);known.add(rel);
    const original=normalize(fs.readFileSync(file,'utf8'));
    const currentText=fs.existsSync(current)?normalize(fs.readFileSync(current,'utf8')):null;
    const status=currentText===null?'Missing':original===currentText?'Identical':original.replaceAll('FM26Access','FM27Access')===currentText?'Identity rename only':'Changed';
    rows.push({project,path:path.relative(root,current).replaceAll('\\','/'),status,originalHash:hash(original),currentHash:currentText===null?null:hash(currentText)});
  }
  for(const file of walk(currentRoot)){
    if(!known.has(path.relative(currentRoot,file)))rows.push({project,path:path.relative(root,file).replaceAll('\\','/'),status:'Added',currentHash:hash(normalize(fs.readFileSync(file,'utf8')))});
  }
}
const counts={};for(const row of rows)counts[row.status]=(counts[row.status]||0)+1;
const newProjects=fs.readdirSync(root,{withFileTypes:true}).filter(e=>e.isDirectory()&&e.name.startsWith('FM27Access.')&&!projects.includes(e.name.slice('FM27Access.'.length))&&fs.existsSync(path.join(root,e.name,e.name+'.csproj'))).map(e=>e.name);
const report=['# FM26 to FM27 source comparison','',
  'Generated by `node scripts/compare-fm26-source.cjs`. Baseline FM26 0.2.16 / `4d38a0256f29b97376845ef59edfcd64d7f165ed`.','',
    'Compares project text sources, normalizing BOM and line endings. Identity-only allows FM26Access to FM27Access. Source equality does not prove native coverage.', '',
  '| Textual result | Files |','| --- | ---: |',...Object.entries(counts).map(([k,v])=>`| ${k} | ${v} |`),'',
    'Additional runtime projects: '+(newProjects.join(', ')||'none')+'.', '',
  '## Changed or missing upstream sources','',
  '| Current file | Result |','| --- | --- |',...rows.filter(r=>['Changed','Missing'].includes(r.status)).map(r=>`| [${r.path}](../../${r.path}) | ${r.status} |`),'',
  '## Files added to imported projects','',
  '| Current file | Result |','| --- | --- |',...rows.filter(r=>r.status==='Added').map(r=>`| [${r.path}](../../${r.path}) | Added |`),'',
    'The JSON report contains every file and its hashes. Compilation and passing tests do not prove complete game integration.',''];
fs.mkdirSync(path.join(root,'artifacts/analysis'),{recursive:true});
fs.writeFileSync(path.join(root,'artifacts/analysis/fm26-source-comparison.json'),JSON.stringify({baseline:'4d38a0256f29b97376845ef59edfcd64d7f165ed',counts,newProjects,files:rows},null,2));
fs.writeFileSync(path.join(root,'artifacts/analysis/fm26-source-comparison.md'),report.join('\n'));
console.log(JSON.stringify({counts,newProjects,changed:rows.filter(r=>r.status==='Changed').map(r=>r.path)}));
